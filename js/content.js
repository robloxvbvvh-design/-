const SUP = { 2: '²', 3: '³', 4: '⁴', 5: '⁵', 6: '⁶' };

function genMath(g) {
  switch (g) {
    case 1: {
      const a = R(1, 10), b = R(1, 9);
      return Math.random() < 0.5 ? N(`${a} + ${b} = ?`, a + b, 2)
        : N(`${a + b} − ${b} = ?`, a, 2);
    }
    case 2: {
      if (Math.random() < 0.4) { const a = R(2, 5), b = R(2, 9); return N(`${a} × ${b} = ?`, a * b, 3); }
      const a = R(11, 60), b = R(5, 39);
      return Math.random() < 0.5 ? N(`${a} + ${b} = ?`, a + b, 10) : N(`${a + b} − ${b} = ?`, a, 10);
    }
    case 3: {
      const a = R(3, 9), b = R(3, 9);
      return Math.random() < 0.6 ? N(`${a} × ${b} = ?`, a * b, 4) : N(`${a * b} : ${a} = ?`, b, 2);
    }
    case 4: {
      const r = Math.random();
      if (r < 0.35) { const a = R(12, 99), b = R(2, 9); return N(`${a} × ${b} = ?`, a * b, 10); }
      if (r < 0.7) { const a = R(2, 9), b = R(2, 9), c = R(2, 9); return N(`${a} + ${b} × ${c} = ?`, a + b * c, 5); }
      const a = R(101, 899), b = R(11, 99); return N(`${a} + ${b} = ?`, a + b, 10);
    }
    case 5: {
      const r = Math.random();
      if (r < 0.4) {
        const d = R(5, 11), x = R(1, d - 3), y = R(1, d - x - 1);
        return T(`${x}/${d} + ${y}/${d} = ?`, `${x + y}/${d}`, `${x + y}/${d * 2}`, `${x + y + 1}/${d}`);
      }
      if (r < 0.7) {
        const a = R(1, 9) / 10 + R(0, 5), b = R(1, 9) / 10;
        const s = Math.round((a + b) * 10) / 10;
        return T(`${fmt(a)} + ${fmt(b)} = ?`, fmt(s), fmt(Math.round((s + 1) * 10) / 10), fmt(Math.round((s - 0.1) * 10) / 10 || 0.2));
      }
      const p = R(2, 12);
      return N(`Периметр квадрата ${4 * p} см. Сторона?`, p, 2, ' см');
    }
    default: {
      const r = Math.random();
      if (r < 0.35) { const a = R(2, 15), b = R(2, 15); return N(`−${a} + ${b} = ?`, b - a, 3); }
      if (r < 0.7) { const p = pick([10, 20, 25, 50]), n = pick([40, 60, 80, 120, 200, 300]); return N(`${p}% от ${n} = ?`, n * p / 100, 5); }
      const a = R(2, 9), b = R(2, 5), c = a * R(2, 6);
      return N(`${a} : ${b} = ${c} : x. x = ?`, c * b / a, 3);
    }
  }
}

function genAlgebra(g) {
  const r = Math.random();
  if (g === 7) {
    if (r < 0.5) { const x = R(1, 9), a = R(2, 6), b = R(1, 15); return N(`${a}x + ${b} = ${a * x + b}. x = ?`, x, 2); }
    const a = R(2, 5), n = R(2, 4); return N(`${a}${SUP[n]} = ?`, a ** n, 6);
  }
  if (g === 8) {
    if (r < 0.5) { const a = R(2, 15); return N(`√${a * a} = ?`, a, 2); }
    const x1 = R(1, 6), x2 = x1 + R(1, 4);
    return T(`Корни x² − ${x1 + x2}x + ${x1 * x2} = 0`, `${x1} и ${x2}`, `${-x1} и ${-x2}`, `${x1} и ${x2 + 1}`);
  }
  if (g === 9) {
    const a1 = R(1, 9), d = R(2, 6), n = R(4, 8);
    if (r < 0.5) return N(`Ар. прогрессия: a₁ = ${a1}, d = ${d}. a${n < 10 ? '₀₁₂₃₄₅₆₇₈₉'[n] : n} = ?`, a1 + (n - 1) * d, d);
    const b = R(2, 3), k = R(3, 5); return N(`Геом. прогрессия: 1, ${b}, ${b * b}, … ${k + 1}-й член?`, b ** k, 4);
  }
  if (g === 10) {
    if (r < 0.5) { const b = pick([2, 3, 5]), k = R(2, b === 2 ? 6 : 3); return N(`log${'₀₁₂₃₄₅'[b]} ${b ** k} = ?`, k, 2); }
    return pick(BANK.algebraHigh.filter(i => i.g <= 10)).item;
  }
  if (r < 0.5) {
    const a = R(2, 5), n = R(2, 4);
    const coef = a * n;
    const pw = n - 1 === 1 ? 'x' : `x${SUP[n - 1]}`;
    return T(`(${a}x${SUP[n]})′ = ?`, `${coef}${pw}`, `${a}${pw}`, `${coef}x${SUP[n]}`);
  }
  return pick(BANK.algebraHigh).item;
}

function genGeometry(g) {
  const r = Math.random();
  if (r < 0.3 || g === 7) {
    const a = R(30, 80), b = R(20, 150 - a);
    return N(`Углы треугольника ${a}° и ${b}°. Третий угол?`, 180 - a - b, 10, '°');
  }
  if (r < 0.6) {
    const [x, y, z] = pick([[3, 4, 5], [6, 8, 10], [5, 12, 13], [8, 15, 17], [9, 12, 15]]);
    return N(`Катеты ${x} и ${y}. Гипотенуза?`, z, 2);
  }
  const a = R(3, 12), b = R(2, 9);
  return Math.random() < 0.5 ? N(`Прямоугольник ${a}×${b}. Площадь?`, a * b, 4)
    : N(`Прямоугольник ${a}×${b}. Периметр?`, 2 * (a + b), 4);
}

function genPhysics() {
  const r = Math.random();
  if (r < 0.33) { const v = pick([40, 50, 60, 80, 90]), t = R(2, 4); return N(`Проехал ${v * t} км за ${t} ч. Скорость?`, v, 10, ' км/ч'); }
  if (r < 0.66) { const m = R(2, 10), a = R(2, 5); return N(`m = ${m} кг, a = ${a} м/с². F = ?`, m * a, 4, ' Н'); }
  const i = R(2, 5), rr = R(2, 10); return N(`I = ${i} А, R = ${rr} Ом. U = ?`, i * rr, 4, ' В');
}

function genInformatics() {
  if (Math.random() < 0.6) {
    const n = R(5, 31);
    return N(`${n.toString(2)}₂ = ?₁₀`, n, 3);
  }
  const n = R(3, 15);
  return T(`${n}₁₀ в двоичной`, n.toString(2), (n + 1).toString(2), (n ^ 2).toString(2));
}

