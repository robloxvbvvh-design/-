const R = (a, b) => Math.floor(Math.random() * (b - a + 1)) + a;
const pick = arr => arr[Math.floor(Math.random() * arr.length)];
const shuffle = arr => {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

// Числовой вопрос: неверные ответы — соседние числа
function numWrongs(a, spread) {
  spread = Math.max(2, spread);
  const s = new Set();
  while (s.size < 2) {
    const v = a + R(1, spread) * (Math.random() < 0.5 ? -1 : 1);
    if (v !== a && (a < 0 || v >= 0)) s.add(v);
  }
  return [...s];
}
const fmt = n => String(n).replace('-', '−').replace('.', ',');
function N(q, a, spread = 3, unit = '') {
  return { q, a: fmt(a) + unit, w: numWrongs(a, spread).map(v => fmt(v) + unit) };
}
const T = (q, a, w1, w2) => ({ q, a, w: [w1, w2] });

